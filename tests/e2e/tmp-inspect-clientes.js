require('dotenv').config({ path: './.env.local' });
const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext();
  const page = await context.newPage();
  page.on('console', msg => console.log(`BROWSER: ${msg.type()} ${msg.text()}`));
  await page.goto('http://localhost:3000/login');
  await page.fill('input[type=email]', process.env.E2E_TEST_EMAIL);
  await page.fill('input[type=password]', process.env.E2E_TEST_PASSWORD);
  await page.click('button[type=submit]');
  await page.waitForURL('**/');
  await page.goto('http://localhost:3000/clientes');
  await page.waitForSelector('h1:has-text("Clientes")');
  console.log('NEW CLIENT BUTTON COUNT', await page.locator('button:has-text("Nuevo cliente")').count());
  console.log('NEW CLIENT VISIBLE', await page.locator('button:has-text("Nuevo cliente")').isVisible());
  await page.locator('button:has-text("Nuevo cliente")').click();
  await page.waitForTimeout(500);
  console.log('MODAL COUNT', await page.locator('h2:has-text("Nuevo cliente")').count());
  console.log('MODAL VISIBLE', await page.locator('h2:has-text("Nuevo cliente")').isVisible());
  console.log('BUTTONS IN MODAL', await page.$$eval('button', els => els.map(b => ({text: b.textContent.trim(), visible: b.offsetParent !== null})).slice(0,20)));
  console.log('FIRST BUTTON HTML', await page.locator('button:has-text("Consumidor final")').first().evaluate(el => el.outerHTML).catch(() => 'none'));
  await browser.close();
})();